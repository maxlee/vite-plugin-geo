import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'fs';
import { join } from 'path';
import { parseCliArgs } from './cli.js';
import {
  applyGeoGenerationPlanToDisk,
  buildGeoGenerationPlan,
  buildGeoGenerationPlanFromDisk,
  generateSkuMd,
  validateGeoOptions,
  validateSkuMdOptions,
} from './geoBuildPipeline.js';
import {
  generateFeedXml,
  generateHumansTxt,
  generateRobotsTxt,
  generateSitemap,
} from './geoGenerator.js';

describe('v0.1.4 public contract', () => {
  const fixtureRoot = join(process.cwd(), 'tempfiles', '__v014-contract__');
  const distDir = join(fixtureRoot, 'dist');

  beforeEach(() => {
    mkdirSync(distDir, { recursive: true });
    writeFileSync(join(fixtureRoot, 'package.json'), JSON.stringify({
      name: 'v014-fixture',
      domain: 'https://example.com',
      author: {},
    }));
    writeFileSync(
      join(distDir, 'index.html'),
      '<!doctype html><html lang="en"><head><title>Example Store</title><meta name="description" content="Independent tea catalog"></head><body><h1>Store</h1></body></html>',
    );
    writeFileSync(
      join(distDir, 'about.html'),
      '<!doctype html><html lang="en"><head><title>About</title><meta name="description" content="About the store"></head><body><h1>About</h1></body></html>',
    );
  });

  afterEach(() => {
    rmSync(fixtureRoot, { recursive: true, force: true });
  });

  it('accepts the v0.1.4 options and rejects removed options', () => {
    expect(validateGeoOptions({
      lastmodStrategy: 'none',
      llmsMdMirrorStyle: 'replace',
      generateRobots: false,
    })).toMatchObject({
      lastmodStrategy: 'none',
      llmsMdMirrorStyle: 'replace',
      generateRobots: false,
    });

    for (const removedOption of [
      'llmsFull',
      'llmsCtx',
      'llmsCtxFull',
      'blockGoogleExtended',
    ]) {
      expect(() => validateGeoOptions({ [removedOption]: true }))
        .toThrow(new RegExp(`${removedOption}.*removed`, 'i'));
    }
  });

  it('requires domain to be an origin-only HTTP(S) URL', () => {
    for (const domain of [
      'https://user:pass@example.com',
      'https://example.com/store',
      'https://example.com/?q=1',
      'https://example.com/#top',
    ]) {
      expect(() => validateGeoOptions({ domain })).toThrow(/origin/i);
    }

    expect(validateGeoOptions({ domain: 'https://example.com/' }).domain)
      .toBe('https://example.com/');
  });

  it('parses new CLI flags and rejects removed flags', () => {
    const parsed = parseCliArgs([
      'generate',
      '--lastmod-strategy',
      'none',
      '--llms-md-mirror-style=replace',
      '--no-generate-robots',
    ]);

    expect(parsed.options).toMatchObject({
      lastmodStrategy: 'none',
      llmsMdMirrorStyle: 'replace',
      generateRobots: false,
    });
    expect(() => parseCliArgs(['--llms-full'])).toThrow(/unknown argument/i);
    expect(() => parseCliArgs(['--block-google-extended'])).toThrow(/unknown argument/i);
  });

  it('generates append-style Markdown discovery links and no speculative sitemap fields', async () => {
    const plan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: { generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    const files = new Map(plan.files.map((file) => [file.filename, file.content]));
    expect(files.has('index.html.md')).toBe(true);
    expect(files.has('about.html.md')).toBe(true);
    expect(files.get('about.html.md')).toMatch(/^<!-- Generated by vite-plugin-geo; source: about\.html -->/);
    expect(files.get('llms.txt')).toContain('https://example.com/about.html.md');
    expect(files.get('sitemap.xml')).not.toMatch(/<(?:lastmod|priority|changefreq)>/);

    const aboutUpdate = plan.htmlUpdates.find((update) => update.filename === 'about.html');
    expect(aboutUpdate?.content).toContain('rel="alternate"');
    expect(aboutUpdate?.content).toContain('type="text/markdown"');
    expect(aboutUpdate?.content).toContain('href="https://example.com/about.html.md"');
    expect(aboutUpdate?.content).toContain('rel="describedby"');
    expect(aboutUpdate?.content).toContain('href="https://example.com/llms.txt"');
  });

  it('uses replace-style mirrors and disables robots by default for a subpath scope', async () => {
    const plan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: {
        routeBasePath: '/docs/',
        llmsMdMirrorStyle: 'replace',
        generateFeed: false,
      },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    const fileNames = plan.files.map(({ filename }) => filename);
    expect(fileNames).toContain('index.md');
    expect(fileNames).toContain('about.md');
    expect(fileNames).not.toContain('robots.txt');
    expect(plan.files.find(({ filename }) => filename === 'llms.txt')?.content)
      .toContain('https://example.com/docs/about.md');
    expect(plan.htmlUpdates.find(({ filename }) => filename === 'about.html')?.content)
      .toContain('href="https://example.com/docs/llms.txt"');
  });

  it('keeps a valid existing Markdown alternate and is idempotent', async () => {
    const source = '<!doctype html><html><head><title>Home</title><meta name="description" content="Home"><link href="/handwritten/home.md" type="text/markdown" rel="alternate"></head><body><h1>Home</h1></body></html>';
    const firstPlan = await buildGeoGenerationPlan({
      projectRoot: fixtureRoot,
      distDir,
      htmlInputs: [{ relativePath: 'index.html', htmlContent: source }],
      options: { domain: 'https://example.com', generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    expect(firstPlan.files.map(({ filename }) => filename)).not.toContain('index.html.md');
    expect(firstPlan.files.find(({ filename }) => filename === 'llms.txt')?.content)
      .toContain('https://example.com/handwritten/home.md');
    const firstHtml = firstPlan.htmlUpdates[0]?.content;
    expect(firstHtml?.match(/type="text\/markdown"/g)).toHaveLength(2);

    const secondPlan = await buildGeoGenerationPlan({
      projectRoot: fixtureRoot,
      distDir,
      htmlInputs: [{ relativePath: 'index.html', htmlContent: firstHtml }],
      options: { domain: 'https://example.com', generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    });
    expect(secondPlan.htmlUpdates).toHaveLength(0);
  });

  it('does not inject discovery links into excluded or noindex pages', async () => {
    writeFileSync(
      join(distDir, 'private.html'),
      '<html><head><title>Private</title><meta name="robots" content="noindex"></head><body>Private</body></html>',
    );
    writeFileSync(
      join(distDir, 'draft.html'),
      '<html><head><title>Draft</title></head><body>Draft</body></html>',
    );

    const plan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: { excludePatterns: ['draft.html'], generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    expect(plan.htmlUpdates.map(({ filename }) => filename)).not.toContain('private.html');
    expect(plan.htmlUpdates.map(({ filename }) => filename)).not.toContain('draft.html');
    expect(plan.files.map(({ filename }) => filename)).not.toContain('private.html.md');
    expect(plan.files.map(({ filename }) => filename)).not.toContain('draft.html.md');
  });

  it('rejects a replace-style mirror collision before writing', async () => {
    writeFileSync(join(distDir, 'about.md'), '# Handwritten About\n');

    await expect(buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: { llmsMdMirrorStyle: 'replace', generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    })).rejects.toThrow(/about\.md.*conflict/i);

    expect(existsSync(join(distDir, 'llms.txt'))).toBe(false);
  });

  it('rejects user-owned generated-file targets before writing any output', async () => {
    writeFileSync(join(distDir, 'llms.txt'), '# Handwritten index\n');

    await expect(buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: { generateFeed: false },
      currentDate: '2026-08-12T00:00:00.000Z',
    })).rejects.toThrow(/llms\.txt.*conflict/i);

    expect(readFileSync(join(distDir, 'llms.txt'), 'utf-8')).toBe('# Handwritten index\n');
    expect(existsSync(join(distDir, 'robots.txt'))).toBe(false);
  });

  it('recognizes its own generated files on a later CLI-style run', async () => {
    const firstPlan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: {},
      currentDate: '2026-08-12T00:00:00.000Z',
    });
    applyGeoGenerationPlanToDisk(firstPlan, { distDir });
    const generatedHtmlPath = join(distDir, 'index.html');
    writeFileSync(
      generatedHtmlPath,
      readFileSync(generatedHtmlPath, 'utf-8').replace(
        '<h1>Store</h1>',
        '<h1>Updated home</h1>',
      ),
    );

    const secondPlan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: {},
      currentDate: '2026-08-13T00:00:00.000Z',
    });

    expect(secondPlan.files.find(({ filename }) => filename === 'llms.txt')?.content)
      .toContain('<!-- Generated by vite-plugin-geo -->');
    expect(secondPlan.files.find(({ filename }) => filename === 'index.html.md')?.content)
      .toContain('# Updated home');
    expect(secondPlan.htmlUpdates).toHaveLength(0);
  });

  it('allows explicit root robots generation for a subpath scope', async () => {
    const plan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: {
        routeBasePath: '/docs/',
        generateRobots: true,
        generateFeed: false,
      },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    expect(plan.files.find(({ filename }) => filename === 'robots.txt')?.content)
      .toContain('Sitemap: https://example.com/docs/sitemap.xml');
  });

  it('does not advertise a sitemap that is disabled and absent', async () => {
    const plan = await buildGeoGenerationPlanFromDisk({
      projectRoot: fixtureRoot,
      distDir,
      options: {
        generateSitemap: false,
        generateFeed: false,
      },
      currentDate: '2026-08-12T00:00:00.000Z',
    });

    expect(plan.files.map(({ filename }) => filename)).not.toContain('sitemap.xml');
    expect(plan.files.find(({ filename }) => filename === 'llms.txt')?.content)
      .not.toContain('[Sitemap]');
    expect(plan.files.find(({ filename }) => filename === 'robots.txt')?.content)
      .not.toContain('Sitemap:');
  });
});

describe('v0.1.4 standards output', () => {
  it('omits lastmod by default and emits it only for explicit strategies', () => {
    const testDir = join(process.cwd(), 'tempfiles', '__v014-sitemap__');
    mkdirSync(testDir, { recursive: true });
    const filePath = join(testDir, 'index.html');
    writeFileSync(filePath, '<html><head><title>Home</title></head></html>');
    try {
      const [defaultSitemap] = generateSitemap(
        'https://example.com',
        [filePath],
        testDir,
        '2026-08-12T00:00:00.000Z',
      );
      const [buildSitemap] = generateSitemap(
        'https://example.com',
        [filePath],
        testDir,
        '2026-08-12T00:00:00.000Z',
        { lastmodStrategy: 'build' },
      );

      expect(defaultSitemap.content).not.toContain('<lastmod>');
      expect(defaultSitemap.content).not.toMatch(/<(?:priority|changefreq)>/);
      expect(buildSitemap.content).toContain('<lastmod>2026-08-12T00:00:00.000Z</lastmod>');

      const splitSitemap = generateSitemap(
        'https://example.com',
        [filePath, join(testDir, 'about.html')],
        testDir,
        '2026-08-12T00:00:00.000Z',
        { sitemapMaxBytes: 210 },
      );
      const sitemapIndex = splitSitemap.find(({ filename }) => filename === 'sitemap_index.xml');
      expect(sitemapIndex?.content).not.toContain('<lastmod>');
    } finally {
      rmSync(testDir, { recursive: true, force: true });
    }
  });

  it('rejects robots.txt content larger than 500 KiB', () => {
    const result = generateRobotsTxt('https://example.com');
    expect(result).toContain('User-agent: *\nAllow: /\n');
    expect(result).not.toContain('\\n');

    expect(() => generateRobotsTxt('https://example.com', {
      robotsDirectives: [`Disallow: /${'x'.repeat(512_000)}`],
    })).toThrow(/500 KiB/i);
  });

  it('generates RSS self discovery and omits unverified item dates', () => {
    const result = generateFeedXml(
      [{
        url: 'https://example.com/about',
        title: 'About',
        description: 'About the site',
      }],
      {
        url: 'https://example.com',
        feedUrl: 'https://example.com/feed.xml',
        title: 'Example',
        description: 'Example feed',
        lang: 'en',
      },
      '2026-08-12T00:00:00.000Z',
    );

    expect(result).toContain('xmlns:atom="http://www.w3.org/2005/Atom"');
    expect(result).toContain('<atom:link href="https://example.com/feed.xml" rel="self" type="application/rss+xml" />');
    expect(result).toContain('<guid isPermaLink="true">https://example.com/about</guid>');
    expect(result).not.toContain('<pubDate>');
  });

  it('omits humans.txt placeholders when package metadata is absent', () => {
    const result = generateHumansTxt({}, '2026-08-12T00:00:00.000Z');

    expect(result).not.toMatch(/\[Your |Build Tools|Developer:\s*$/m);
    expect(result).toContain('Last update: 2026-08-12');
  });

  it('generates SKU.md 1.0.0-beta as strict plain Markdown', () => {
    const options = {
      merchantName: 'Example Store',
      summary: 'Independent tea catalog.',
      catalog: [
        { label: 'All teas', url: 'https://example.com/catalog' },
      ],
    };

    expect(validateSkuMdOptions(options, {
      siteUrl: 'https://example.com',
      routeBasePath: '/',
    })).toEqual(options);

    const result = generateSkuMd(options, { siteUrl: 'https://example.com' });
    expect(result).toBe([
      '# Example Store',
      '',
      '> Independent tea catalog.',
      '',
      'SKU.md: [1.0.0-beta](https://sku.md/spec/1.0.0-beta/)',
      'Website: [Example Store](https://example.com/)',
      '',
      '## Catalog',
      '',
      '- [All teas](https://example.com/catalog)',
      '',
    ].join('\n'));
    expect(result).not.toContain('---');
  });

  it('rejects invalid or obsolete SKU.md fields', () => {
    const context = { siteUrl: 'https://example.com', routeBasePath: '/' };
    expect(() => validateSkuMdOptions({
      merchantName: 'Store',
      summary: 'Catalog',
      catalog: [],
    }, context)).toThrow(/catalog/i);
    expect(() => validateSkuMdOptions({
      merchantName: 'Store',
      summary: 'Catalog',
      catalog: [{ label: 'Other', url: 'https://other.example/catalog' }],
    }, context)).toThrow(/same origin/i);
    expect(() => validateSkuMdOptions({
      merchantName: 'Store',
      summary: 'Catalog',
      catalog: [{ label: 'Catalog', url: 'https://example.com/catalog' }],
      market: 'US',
    }, context)).toThrow(/market.*removed/i);
  });

  it('derives missing SKU.md title and summary from homepage metadata', async () => {
    const fixtureRoot = join(process.cwd(), 'tempfiles', '__v014-sku-fallback__');
    const distDir = join(fixtureRoot, 'dist');
    mkdirSync(distDir, { recursive: true });
    writeFileSync(join(fixtureRoot, 'package.json'), JSON.stringify({
      name: 'sku-fallback',
      domain: 'https://example.com',
    }));
    writeFileSync(
      join(distDir, 'index.html'),
      '<html><head><title>Homepage Store</title><meta name="description" content="Homepage catalog summary"></head><body></body></html>',
    );
    try {
      const plan = await buildGeoGenerationPlanFromDisk({
        projectRoot: fixtureRoot,
        distDir,
        options: {
          generateFeed: false,
          skuMd: {
            catalog: [{ label: 'Catalog', url: 'https://example.com/catalog' }],
          },
        },
        currentDate: '2026-08-12T00:00:00.000Z',
      });
      const sku = plan.files.find(({ filename }) => filename === 'sku.md')?.content;
      expect(sku).toContain('# Homepage Store');
      expect(sku).toContain('> Homepage catalog summary');
    } finally {
      rmSync(fixtureRoot, { recursive: true, force: true });
    }
  });
});
