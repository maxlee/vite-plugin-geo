function markGeneratedFile(filename, content) {
  if (content.includes(GENERATED_FILE_MARKER)) {
    return content;
  }
  if (filename === 'feed.xml') {
    return content.replace(
      /^<\?xml version="1\.0" encoding="UTF-8"\?>/,
      `$&\n<!-- ${GENERATED_FILE_MARKER} -->`,
    );
  }
  if (filename === 'robots.txt') {
    return `# ${GENERATED_FILE_MARKER}\n${content}`;
  }
  if (filename === 'humans.txt') {
    return `/* ${GENERATED_FILE_MARKER} */\n${content}`;
  }
  return `${content.trimEnd()}\n\n<!-- ${GENERATED_FILE_MARKER} -->\n`;
}

function validateGeneratedFileLimits(filename, content) {
  if (filename === 'robots.txt' && Buffer.byteLength(content, 'utf-8') > 500 * 1024) {
    throw new Error('robots.txt exceeds the 500 KiB processing limit.');
  }
  if (filename !== 'sku.md') return;
  if (Buffer.byteLength(content, 'utf-8') > SKU_MD_MAX_BYTES) {
    throw new Error('sku.md exceeds the 65,536 byte limit.');
  }
  content.split('\n').forEach((line, index) => {
    if (Buffer.byteLength(line, 'utf-8') > SKU_MD_MAX_LINE_BYTES) {
      throw new Error(`sku.md line ${index + 1} exceeds the 8,192 byte limit.`);
    }
  });
}

function isValidLanguageTag(languageTag, { allowXDefault = false } = {}) {
  if (allowXDefault && languageTag === 'x-default') return true;
  if (!/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(languageTag)) return false;
  try {
    Intl.getCanonicalLocales(languageTag);
    return true;
  } catch {
    return false;
  }
}

/**
 * Summarize exclusion reasons as `reason × count` for zero-page diagnostics.
 */
export function summarizeExcludedReasons(excludedDetails = []) {
  const counts = new Map();
  excludedDetails.forEach(({ reason = 'excluded' }) => {
    counts.set(reason, (counts.get(reason) || 0) + 1);
  });
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([reason, count]) => `${reason} × ${count}`)
    .join('、');
}

/**
 * Format the final build decisions for `debug: true` output.
 * Mirrors the information needed to diagnose silent skips without reading source.
 */
export function formatGeoDebugSummary({
  projectRoot,
  distDir,
  sourceHtmlDir,
  report = {},
} = {}) {
  const lines = ['🔍 [GEO debug] Generation summary'];
  lines.push(`   siteUrl=${report.siteUrl || ''} routeBasePath=${report.routeBasePath ?? ''}`);
  lines.push(`   projectRoot=${projectRoot} distDir=${distDir} sourceHtmlDir=${sourceHtmlDir}`);
  lines.push(
    `   pages: total=${report.totalHtmlFiles ?? 0} included=${report.includedHtmlFiles ?? 0} `
    + `excluded=${report.excludedHtmlFiles ?? 0}`,
  );
  if (report.excludedDetails?.length) {
    lines.push(`   exclusion reasons: ${summarizeExcludedReasons(report.excludedDetails)}`);
  }
  if (report.routeConflicts?.length) {
    lines.push(
      '   route conflicts: '
      + report.routeConflicts.map(({ route, chosen }) => `${route} → ${chosen}`).join('、'),
    );
  }
  const sitemap = report.sitemapCompatibility;
  if (sitemap) {
    lines.push(
      `   sitemap: detected=${sitemap.detected} decision=${sitemap.decision} `
      + `url=${sitemap.sitemapUrl} reason=${sitemap.reason}`,
    );
  }
  const files = report.generatedFiles || [];
  if (files.length > 0) {
    lines.push(`   generated: ${files.map(({ filename, size }) => `${filename} (${size}B)`).join('、')}`);
    const mirrors = files
      .filter(({ filename }) => filename.endsWith('.md'))
      .slice(0, 5)
      .map(({ filename }) => filename);
    if (mirrors.length > 0) {
      lines.push(`   markdown mirrors: ${mirrors.join('、')}${files.length > 5 ? '…' : ''}`);
    }
  }
  return lines.join('\n');
}

function resolvePackageJsonPath(projectRoot, packageJsonPath) {
  if (packageJsonPath === false) {
    return false;
  }
  const configuredPath = packageJsonPath || './package.json';
  return isAbsolute(configuredPath) ? configuredPath : resolve(projectRoot, configuredPath);
}

function readPackageJson(packageJsonPath) {
  if (!packageJsonPath) {
    return null;
  }
  try {
    return JSON.parse(readFileSync(packageJsonPath, 'utf-8'));
  } catch {
    return null;
  }
}

function resolveSiteUrl(options, packageJson) {
  if (Object.prototype.hasOwnProperty.call(options, 'domain') && options.domain !== undefined) {
    return normalizeSiteDomain(options.domain, 'domain');
  }
  if (packageJson && Object.prototype.hasOwnProperty.call(packageJson, 'domain')) {
    return normalizeSiteDomain(packageJson.domain, 'package.json "domain"');
  }
  throw new Error('Missing required domain. Configure geo({ domain: \'https://example.com\' }) or add "domain" to package.json.');
}

function matchGlob(pattern, value) {
  const regexPattern = String(pattern)
    .replace(/[.+?^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*/g, '___DOUBLESTAR___')
    .replace(/\*/g, '[^/]*')
    .replace(/___DOUBLESTAR___/g, '.*');
  return new RegExp(`^${regexPattern}$`).test(value);
}

function dedupePageInputs(inputs, options) {
  const groups = new Map();
  inputs.forEach((input) => {
    const relativePath = normalizeFilePath(input.relativePath);
    const pagePath = resolvePagePath(relativePath, options);
    if (!groups.has(pagePath)) groups.set(pagePath, []);
    groups.get(pagePath).push({ ...input, relativePath, pagePath });
  });
  return resolvePagePathConflicts(groups, options);
}

function filterPageModels(pageModels, options) {
  const customPatterns = Array.isArray(options.excludePatterns) ? options.excludePatterns : [];
  const included = [];
  const excluded = [];

  pageModels.forEach((page) => {
    const fileName = basename(page.relativePath);
    let reason = '';
    if (DEFAULT_EXCLUDE_PATTERNS.includes(fileName)) {
      reason = 'default exclude';
    } else if (customPatterns.some((pattern) => (
      matchGlob(pattern, page.relativePath) || matchGlob(pattern, fileName)
    ))) {
      reason = 'exclude pattern';
    } else if (page.noindex) {
      reason = 'contains noindex meta tag';
    }

    if (reason) {
      excluded.push({ ...page, excludeReason: reason });
    } else {
      included.push(page);
    }
  });

  return { included, excluded };
}

function decodeXmlEntities(value) {
  return String(value)
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&')
    .trim();
}

function inspectSitemapContent(content) {
  const source = String(content || '');
  const isIndex = /<sitemapindex\b/i.test(source);
  if (!isIndex && !/<urlset\b/i.test(source)) {
    return null;
  }
  const locs = [];
  const pattern = /<loc>\s*([\s\S]*?)\s*<\/loc>/gi;
  let match;
  while ((match = pattern.exec(source)) !== null) {
    const loc = decodeXmlEntities(match[1]);
    if (loc) locs.push(loc);
  }
  return { isIndex, locCount: locs.length, samples: locs.slice(0, 3) };
}

function findExistingSitemap(outputAssets = []) {
  const candidates = outputAssets
    .map(({ filename, content, source }) => {
      const inspected = inspectSitemapContent(content);
      if (!inspected) return null;
      return {
        filename: normalizeFilePath(filename),
        locCount: inspected.locCount,
        samples: inspected.samples,
        isIndex: inspected.isIndex,
        managed: String(content || '').includes(GENERATED_FILE_MARKER),
        source: source || 'bundle',
      };
    })
    .filter(Boolean)
    .sort((a, b) => {
      if (a.isIndex !== b.isIndex) return a.isIndex ? -1 : 1;
      return a.filename.localeCompare(b.filename);
    });
  return candidates[0] || null;
}

function describeExistingSitemap(existing) {
  const sourceLabel = existing.source === 'publicDir' ? 'publicDir' : '构建产物';
  const locator = existing.samples.length > 0
    ? `，样例：${existing.samples.join('、')}`
    : '';
  return `${existing.filename}（来源：${sourceLabel}，${existing.locCount} 条 <loc>${existing.managed ? '，由 vite-plugin-geo 生成' : '，疑似由其他插件生成'}${locator}）`;
}

function sitemapConflictError(existing) {
  return new Error(
    `Detected an existing sitemap ${describeExistingSitemap(existing)}. `
    + "Another plugin (or a public/ file) generated it, and vite-plugin-geo will not overwrite it silently. "
    + "Set sitemapConflict: 'overwrite' (CLI: --sitemap-conflict overwrite) to replace it, "
    + "set sitemapConflict: 'preserve' to keep it, or remove the other sitemap generator.",
  );
}

function resolveSitemapBehavior(options, outputAssets) {
  const existing = findExistingSitemap(outputAssets);
  const sitemapUrlExplicit = typeof options.sitemapUrl === 'string' && options.sitemapUrl.trim() !== '';
  const conflictPolicy = options.sitemapConflict;
  const explicitGenerate = typeof options.generateSitemap === 'boolean'
    ? options.generateSitemap
    : null;

  let shouldGenerateSitemap;
  let decision;
  let reason;

  if (explicitGenerate === false) {
    shouldGenerateSitemap = false;
    decision = 'disabled';
    reason = 'generateSitemap=false';
  } else if (!existing) {
    shouldGenerateSitemap = true;
    decision = 'generate';
    reason = 'no existing sitemap detected';
  } else if (conflictPolicy === 'error') {
    throw sitemapConflictError(existing);
  } else if (conflictPolicy === 'overwrite') {
    shouldGenerateSitemap = true;
    decision = 'overwrite';
    reason = "sitemapConflict='overwrite'";
  } else if (conflictPolicy === 'preserve') {
    shouldGenerateSitemap = false;
    decision = 'preserve';
    reason = explicitGenerate === true
      ? "sitemapConflict='preserve' overrides generateSitemap=true"
      : "sitemapConflict='preserve'";
  } else if (existing.managed) {
    shouldGenerateSitemap = true;
    decision = 'regenerate';
    reason = 'existing sitemap was generated by vite-plugin-geo';
  } else if (explicitGenerate === true) {
    throw sitemapConflictError(existing);
  } else {
    shouldGenerateSitemap = false;
    decision = 'preserve';
    reason = 'auto-detected external sitemap; set sitemapConflict to change behavior';
  }

  return {
    detected: Boolean(existing),
    existing,
    decision,
    reason,
    shouldGenerateSitemap,
    sitemapUrl: sitemapUrlExplicit
      ? options.sitemapUrl.trim()
      : (existing?.filename || 'sitemap.xml'),
    sitemapUrlExplicit,
  };
}

/**
 * Log the detected sitemap and the decision taken, including samples so a
 * silent skip never hides a third-party sitemap again.
 */
export function logSitemapCompatibility(compatibility, logger = console) {
  if (!compatibility) return;
  const { detected, existing, decision, reason, sitemapUrl } = compatibility;

  if (!detected) {
    logger.log(`[vite-plugin-geo] 未检测到现有 sitemap，将生成 ${sitemapUrl}。`);
    return;
  }

  const detail = describeExistingSitemap(existing);
  if (decision === 'preserve') {
    logger.warn(`[vite-plugin-geo] 保留现有 sitemap：${detail}。原因：${reason}。`);
  } else if (decision === 'overwrite') {
    logger.warn(`[vite-plugin-geo] 覆盖现有 sitemap：${detail}。原因：${reason}。`);
  } else if (decision === 'regenerate') {
    logger.log(`[vite-plugin-geo] 重新生成 sitemap，替换先前的生成文件：${detail}。`);
  } else if (decision === 'disabled') {
    logger.log('[vite-plugin-geo] sitemap 生成已禁用（generateSitemap=false）。');
  }
}

function validateStringArray(options, key, errors) {
  if (options[key] === undefined) return;
  if (!Array.isArray(options[key])) {
    errors.push(`Option '${key}' must be an array.`);
    return;
  }
  options[key].forEach((value, index) => {
    if (typeof value !== 'string') {
      errors.push(`${key}[${index}] must be a string.`);
    }
  });
}

export function validateGeoOptions(options = {}) {
  const errors = [];
  REMOVED_GEO_OPTIONS.forEach((key) => {
    if (Object.prototype.hasOwnProperty.call(options, key)) {
      errors.push(`Option '${key}' was removed in v0.1.4.`);
    }
  });
  const booleanOptions = [
    'prettyUrls',
    'sitemapIndex',
    'llmsMdMirror',
    'generateHumans',
    'generateFeed',
    'generateRobots',
    'generateSitemap',
    'debug',
    'audit',
    'hreflangFromHtml',
  ];
  booleanOptions.forEach((key) => {
    if (options[key] !== undefined && typeof options[key] !== 'boolean') {
      errors.push(`Option '${key}' must be a boolean.`);
    }
  });

  ['domain', 'distDir', 'routeBasePath', 'lastmodStrategy', 'sourceHtmlDir', 'sitemapUrl', 'llmsMdMirrorStyle'].forEach((key) => {
    if (options[key] !== undefined && typeof options[key] !== 'string') {
      errors.push(`Option '${key}' must be a string.`);
    }
  });
  if (
    options.packageJsonPath !== undefined
    && options.packageJsonPath !== false
    && typeof options.packageJsonPath !== 'string'
  ) {
    errors.push("Option 'packageJsonPath' must be a string or false.");
  }
  if (typeof options.domain === 'string' && options.domain.trim()) {
    try {
      normalizeSiteDomain(options.domain, 'domain');
    } catch (error) {
      errors.push(error.message);
    }
  }
  if (typeof options.routeBasePath === 'string' && options.routeBasePath.trim()) {
    try {
      normalizeRouteBasePath(options.routeBasePath, { source: 'routeBasePath' });
    } catch (error) {
      errors.push(error.message);
    }
  }
  ['sitemapMaxBytes'].forEach((key) => {
    if (options[key] !== undefined && (typeof options[key] !== 'number' || !Number.isFinite(options[key]))) {
      errors.push(`Option '${key}' must be a finite number.`);
    }
  });
  if (options.sitemapMaxBytes !== undefined && options.sitemapMaxBytes <= 0) {
    errors.push("Option 'sitemapMaxBytes' must be greater than zero.");
  }
  ['stripPathPrefixes', 'excludePatterns', 'robotsDirectives', 'lastmodIgnore'].forEach(
    (key) => validateStringArray(options, key, errors),
  );
  if (options.lastmodStrategy !== undefined && !['none', 'file-mtime', 'build', 'git'].includes(options.lastmodStrategy)) {
    errors.push("Option 'lastmodStrategy' must be one of: none, file-mtime, build, git.");
  }
  if (options.llmsMdMirrorStyle !== undefined && !['append', 'replace'].includes(options.llmsMdMirrorStyle)) {
    errors.push("Option 'llmsMdMirrorStyle' must be one of: append, replace.");
  }
  if (options.sitemapConflict !== undefined && !['preserve', 'error', 'overwrite'].includes(options.sitemapConflict)) {
    errors.push("Option 'sitemapConflict' must be one of: preserve, error, overwrite.");
  }
  if (options.routeConflict !== undefined && !['error', 'first', 'last'].includes(options.routeConflict)) {
    errors.push("Option 'routeConflict' must be one of: error, first, last.");
  }
  if (options.auditFailOn !== undefined && !['warning', 'advice'].includes(options.auditFailOn)) {
    errors.push("Option 'auditFailOn' must be one of: warning, advice.");
  }
  if (options.lastmodResolver !== undefined && typeof options.lastmodResolver !== 'function') {
    errors.push("Option 'lastmodResolver' must be a function.");
  }
  if (options.llmsClassify !== undefined && typeof options.llmsClassify !== 'function') {
    errors.push("Option 'llmsClassify' must be a function.");
  }
  if (
    options.llmsSections !== undefined
    && (
      !options.llmsSections
      || typeof options.llmsSections !== 'object'
      || Array.isArray(options.llmsSections)
    )
  ) {
    errors.push("Option 'llmsSections' must be an object.");
  }
  if (options.hreflang !== undefined) {
    if (!options.hreflang || typeof options.hreflang !== 'object' || Array.isArray(options.hreflang)) {
      errors.push("Option 'hreflang' must be an object.");
    } else {
      Object.entries(options.hreflang).forEach(([languageTag, urlPattern]) => {
        if (!isValidLanguageTag(languageTag, { allowXDefault: true })) {
          errors.push(`Invalid BCP 47 language code in hreflang: '${languageTag}'.`);
        }
        if (typeof urlPattern !== 'string') {
          errors.push(`hreflang URL pattern for '${languageTag}' must be a string.`);
        }
      });
    }
  }
  (options.robotsDirectives || []).forEach((directive) => {
    if (/[\u0000-\u001F\u007F]/.test(String(directive))) {
      errors.push('robotsDirectives must not contain control characters.');
    }
  });

  if (errors.length > 0) {
    throw new Error(`Invalid GEO configuration:\n- ${errors.join('\n- ')}`);
  }
  return options;
}

export function validateSkuMdOptions(options, context) {
  if (!options || typeof options !== 'object' || Array.isArray(options)) {
    throw new Error('skuMd must be an object.');
  }
  REMOVED_SKU_OPTIONS.forEach((key) => {
    if (Object.prototype.hasOwnProperty.call(options, key)) {
      throw new Error(`skuMd.${key} was removed in v0.1.4.`);
    }
  });

  const merchantName = options.merchantName ?? context.merchantName;
  const summary = options.summary ?? context.summary;
  if (typeof merchantName !== 'string' || !merchantName.trim()) {
    throw new Error('skuMd.merchantName must be a non-empty string.');
  }
  if (typeof summary !== 'string' || !summary.trim()) {
    throw new Error('skuMd.summary must be a non-empty string.');
  }
  const siteUrl = new URL(context.siteUrl);
  if (siteUrl.protocol !== 'https:') {
    throw new Error('sku.md requires an HTTPS site URL.');
  }
  const routeBasePath = context.routeBasePath || '';
  if (
    !['', '/', './'].includes(routeBasePath)
    || (siteUrl.pathname && siteUrl.pathname !== '/')
    || siteUrl.search
    || siteUrl.hash
  ) {
    throw new Error('sku.md can only be generated for a site deployed at the domain root.');
  }

  if (!Array.isArray(options.catalog) || options.catalog.length === 0) {
    throw new Error('skuMd.catalog must be a non-empty array.');
  }
  options.catalog.forEach((entry, index) => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      throw new Error(`skuMd.catalog[${index}] must be an object.`);
    }
    if (typeof entry.label !== 'string' || !entry.label.trim()) {
      throw new Error(`skuMd.catalog[${index}].label must be a non-empty string.`);
    }
    let catalogUrl;
    try {
      catalogUrl = new URL(entry.url);
    } catch {
      throw new Error(`skuMd.catalog[${index}].url must be an absolute HTTPS URL.`);
    }
    if (catalogUrl.protocol !== 'https:' || catalogUrl.username || catalogUrl.password) {
      throw new Error(`skuMd.catalog[${index}].url must be an absolute HTTPS URL without credentials.`);
    }
    if (catalogUrl.origin !== siteUrl.origin) {
      throw new Error(`skuMd.catalog[${index}].url must use the same origin as the configured site.`);
    }
  });

  for (const [field, value] of [['merchantName', merchantName], ['summary', summary]]) {
    if (/\r|\n|<|>/.test(value)) {
      throw new Error(`skuMd.${field} must be a single Markdown-safe line without raw HTML.`);
    }
  }
  options.catalog.forEach((entry, index) => {
    if (/\r|\n|<|>|\[|\]|\(|\)/.test(entry.label)) {
      throw new Error(`skuMd.catalog[${index}].label must be a Markdown-safe label.`);
    }
  });

  return {
    ...options,
    merchantName: merchantName.trim(),
    summary: summary.trim(),
    catalog: options.catalog.map((entry) => ({
      label: entry.label.trim(),
      url: new URL(entry.url).toString(),
    })),
  };
}

export function generateSkuMd(options, context) {
  const normalizedSiteUrl = new URL(context.siteUrl);
  normalizedSiteUrl.pathname = '/';
  normalizedSiteUrl.search = '';
  normalizedSiteUrl.hash = '';
  const siteRoot = normalizedSiteUrl.toString();
  const lines = [
    `# ${options.merchantName}`,
    '',
    `> ${options.summary}`,
    '',
    `SKU.md: [${SKU_MD_VERSION}](https://sku.md/spec/${SKU_MD_VERSION}/)`,
    `Website: [${options.merchantName}](${siteRoot})`,
    '',
    '## Catalog',
    '',
  ];
  options.catalog.forEach(({ label, url }) => lines.push(`- [${label}](${url})`));
  lines.push('');

  const content = lines.join('\n');
  if (Buffer.byteLength(content, 'utf-8') > SKU_MD_MAX_BYTES) {
    throw new Error('sku.md exceeds the 65,536 byte limit.');
  }
  content.split('\n').forEach((line, index) => {
    if (Buffer.byteLength(line, 'utf-8') > SKU_MD_MAX_LINE_BYTES) {
      throw new Error(`sku.md line ${index + 1} exceeds the 8,192 byte limit.`);
    }
  });
  return content;
}

function isLastmodIgnored(page, options) {
  const patterns = Array.isArray(options.lastmodIgnore) ? options.lastmodIgnore : [];
  return patterns.some((pattern) => (
    matchGlob(pattern, page.relativePath) || matchGlob(pattern, page.pagePath || '')
  ));
}

function resolvePageLastmod(page, distDir, options, currentDate, onWarning) {
  if (typeof options.lastmodResolver === 'function') {
    let resolved;
    try {
      resolved = options.lastmodResolver(page);
    } catch (error) {
      throw new Error(`lastmodResolver failed for ${page.relativePath}: ${error.message}`);
    }
    if (resolved === null) return null;
    if (resolved instanceof Date) {
      return Number.isNaN(resolved.getTime()) ? null : resolved.toISOString();
    }
    if (typeof resolved === 'string' && resolved.trim()) {
      return resolved.trim();
    }
  }

  const strategy = options.lastmodStrategy || 'none';
  if (strategy === 'none' || isLastmodIgnored(page, options)) {
    return null;
  }

  if (page.mtime) return page.mtime;

  const sourcePath = resolveLastmodSourcePath(page.filePath, distDir, options);
  return extractLastmod(
    sourcePath || page.filePath,
    strategy,
    currentDate,
    { onWarning },
  );
}

function createPageModels(htmlInputs, distDir, options, currentDate) {
  const { selected: dedupedInputs, conflicts } = dedupePageInputs(htmlInputs, options);
  const lastmodWarnings = [];
  const models = dedupedInputs.map((input) => {
    const analyzed = analyzeHtmlPage(input.htmlContent, { audit: options.audit !== false });
    const filePath = input.filePath || resolve(distDir, input.relativePath);
    const relativePath = normalizeFilePath(input.relativePath);
    const pagePath = resolvePagePath(input.relativePath, options);
    const page = {
      ...input,
      ...analyzed,
      filePath,
      relativePath,
      pagePath,
      mtime: input.mtime || null,
    };
    page.mtime = resolvePageLastmod(page, distDir, options, currentDate, (message) => {
      lastmodWarnings.push({ path: relativePath, message });
    });
    return page;
  });

  if (lastmodWarnings.length > 0) {
    if (options.debug === true) {
      lastmodWarnings.forEach(({ message }) => console.warn(message));
    } else {
      const samples = lastmodWarnings.slice(0, 5).map(({ path }) => path).join('、');
      const more = lastmodWarnings.length > 5 ? ` 等 ${lastmodWarnings.length} 个页面` : '';
      console.warn(
        `⚠️  [Non-fatal] Lastmod unavailable for ${lastmodWarnings.length} page(s) `
        + `(strategy=${options.lastmodStrategy || 'none'}): ${samples}${more}. Enable debug for details.`,
      );
    }
  }

  return { models, conflicts };
}

function listExistingOutputAssets(distDir) {
  if (!existsSync(distDir)) return [];
  const assets = [];
  const visit = (directory) => {
    readdirSync(directory, { withFileTypes: true }).forEach((entry) => {
      const entryPath = join(directory, entry.name);
      if (entry.isDirectory()) {
        visit(entryPath);
      } else if (entry.isFile()) {
        if (!/\.(?:html?|md|txt|xml)$/i.test(entry.name)) return;
        assets.push({
          filename: normalizeFilePath(relative(distDir, entryPath)),
          content: readFileSync(entryPath, 'utf-8'),
        });
      }
    });
  };
  visit(distDir);
  return assets;
}

export function logRobotsPreservation(compatibility, logger) {
  if (!compatibility?.preserved) return;
  const message = '[vite-plugin-geo] Preserved existing robots.txt; skipped generation.';
  if (compatibility.directivesIgnored) {
    logger.warn(`${message} robotsDirectives were not applied to the existing file.`);
  } else {
    logger.log(message);
  }
}

export async function buildGeoGenerationPlan({
  projectRoot,
  distDir,
  htmlInputs,
  outputAssets = [],
  options = {},
  currentDate = new Date().toISOString(),
}) {
  validateGeoOptions(options);
  const routeBasePath = normalizeRouteBasePath(options.routeBasePath);
  const stripPathPrefixes = options.stripPathPrefixes || ['src/pages/'];
  const sourceHtmlDir = isAbsolute(options.sourceHtmlDir || '')
    ? options.sourceHtmlDir
    : resolve(projectRoot, options.sourceHtmlDir || 'src/pages');
  const packageJsonPath = resolvePackageJsonPath(projectRoot, options.packageJsonPath);
  const packageJson = readPackageJson(packageJsonPath);
  const siteUrl = resolveSiteUrl(options, packageJson);
  const normalizedOptions = {
    ...options,
    projectRoot,
    routeBasePath,
    stripPathPrefixes,
    sourceHtmlDir,
    prettyUrls: options.prettyUrls !== false,
    sitemapIndex: options.sitemapIndex !== false,
    lastmodStrategy: options.lastmodStrategy || 'none',
    llmsMdMirrorStyle: options.llmsMdMirrorStyle || 'append',
  };
  const { models: allPageModels, conflicts: routeConflicts } = createPageModels(
    htmlInputs,
    distDir,
    normalizedOptions,
    currentDate,
  );
  const { included: pageModels, excluded } = filterPageModels(allPageModels, normalizedOptions);
  const excludedDetails = excluded.map((page) => ({
    path: page.relativePath,
    reason: page.excludeReason || 'excluded',
  }));
  (options.audit !== false ? allPageModels : pageModels).forEach((page) => {
    page.pageUrl = composePageUrl(siteUrl, page.pagePath, routeBasePath);
    if (options.audit !== false) {
      page.filePageUrl = composePageUrl(siteUrl, resolvePagePath(page.relativePath, {
        ...normalizedOptions,
        prettyUrls: false,
      }), routeBasePath);
    }
  });
  if (pageModels.length === 0) {
    return {
      files: [],
      htmlUpdates: [],
      report: {
        totalHtmlFiles: allPageModels.length,
        includedHtmlFiles: 0,
        excludedHtmlFiles: excluded.length,
        excludedDetails,
        routeConflicts,
        siteUrl,
        routeBasePath,
        ...(options.audit !== false ? { audit: { checkedPages: 0, diagnostics: [] } } : {}),
      },
    };
  }

  const homePage = pageModels.find((page) => page.pagePath === '') || pageModels[0];
  const siteMetadata = {
    url: siteUrl,
    title: homePage.title || 'My Site',
    description: homePage.description || 'Site description',
    lang: homePage.lang || 'en',
  };
  const existingAssets = new Map(outputAssets.map(({ filename, content }) => [
    normalizeFilePath(filename),
    String(content),
  ]));
  const hasExistingRobots = existingAssets.has('robots.txt');
  const userRobots = hasExistingRobots
    && !/^# Generated by vite-plugin-geo(?:\r?\n|$)/.test(existingAssets.get('robots.txt'));
  const preserveRobots = userRobots && options.generateRobots === undefined;
  if (userRobots && options.generateRobots === true) {
    throw new Error('Generated output path robots.txt conflicts with an existing user file. Set generateRobots: false (CLI: --no-generate-robots) to keep it, or remove the existing robots.txt source to let the plugin generate it.');
  }
  const shouldGenerateRobots = !preserveRobots
    && (options.generateRobots ?? (routeBasePath === '' || routeBasePath === '/'));
  const robotsCompatibility = {
    preserved: preserveRobots,
    directivesIgnored: preserveRobots && (options.robotsDirectives?.length || 0) > 0,
  };
  const llmsUrl = composePageUrl(siteUrl, 'llms.txt', routeBasePath);
  pageModels.forEach((page) => {
    const pageUrl = page.pageUrl;
    const mirrorRelativePath = resolveMarkdownMirrorPath(
      page.pagePath,
      normalizedOptions.llmsMdMirrorStyle,
    );
    const generatedMarkdownUrl = normalizedOptions.llmsMdMirror !== false
      ? composePageUrl(siteUrl, mirrorRelativePath, routeBasePath)
      : null;
    const existingMarkdownUrl = resolveMarkdownAlternateUrl(page.htmlContent, pageUrl);
    const hasManagedMirror = Boolean(
      generatedMarkdownUrl
      && existingMarkdownUrl === generatedMarkdownUrl
      && existingAssets.get(mirrorRelativePath)?.startsWith(
        `<!-- ${GENERATED_FILE_MARKER}; source: `,
      )
    );
    page.mirrorRelativePath = mirrorRelativePath;
    page.markdownUrl = existingMarkdownUrl || generatedMarkdownUrl;
    page.hasExistingMarkdownAlternate = Boolean(existingMarkdownUrl) && !hasManagedMirror;
  });
  const pageModelMap = new Map(pageModels.map((page) => [page.filePath, page]));
  const sitemapCompatibility = resolveSitemapBehavior(normalizedOptions, outputAssets);
  const generatorOptions = {
    ...normalizedOptions,
    pageModels: pageModelMap,
    sitemapUrl: sitemapCompatibility.sitemapUrl,
    includeSitemap: sitemapCompatibility.shouldGenerateSitemap
      || sitemapCompatibility.detected
      || sitemapCompatibility.sitemapUrlExplicit,
    generateRobots: shouldGenerateRobots,
    includeRobots: shouldGenerateRobots || hasExistingRobots,
  };
  const files = [];
  const plannedFilenames = new Set();
  const addFile = (filename, content, {
    markManaged = true,
    protectExisting = true,
  } = {}) => {
    if (typeof content !== 'string') {
      throw new Error(`Generated ${filename} content must be a string.`);
    }
    const normalizedFilename = normalizeFilePath(filename);
    const generatedContent = markManaged
      ? markGeneratedFile(normalizedFilename, content)
      : content;
    validateGeneratedFileLimits(normalizedFilename, generatedContent);
    if (plannedFilenames.has(normalizedFilename)) {
      throw new Error(`Generated output path conflict: ${normalizedFilename}.`);
    }
    const existingContent = existingAssets.get(normalizedFilename);
    const isPriorGeneratedFile = existingContent?.includes(GENERATED_FILE_MARKER);
    if (
      protectExisting
      && existingContent !== undefined
      && existingContent !== generatedContent
      && !isPriorGeneratedFile
    ) {
      throw new Error(`Generated output path ${normalizedFilename} conflicts with an existing user file.`);
    }
    plannedFilenames.add(normalizedFilename);
    files.push({ filename: normalizedFilename, content: generatedContent });
  };

  if (sitemapCompatibility.shouldGenerateSitemap) {
    const sitemapFiles = generateSitemap(
      siteMetadata.url,
      pageModels.map((page) => page.filePath),
      distDir,
      currentDate,
      generatorOptions,
    );
    if (!sitemapCompatibility.sitemapUrlExplicit) {
      generatorOptions.sitemapUrl = resolveGeneratedSitemapUrl(sitemapFiles);
    }
    sitemapFiles.forEach(({ filename, content }) => addFile(filename, content, {
      markManaged: true,
      protectExisting: false,
    }));
  }

  if (generatorOptions.llmsMdMirror !== false) {
    pageModels
      .filter((page) => !page.hasExistingMarkdownAlternate)
      .forEach((page) => addFile(
        page.mirrorRelativePath,
        `<!-- Generated by vite-plugin-geo; source: ${page.relativePath} -->\n\n${page.markdown}\n`,
        { markManaged: false },
      ));
  }

  let skuMdOptions = null;
  if (options.skuMd !== undefined) {
    skuMdOptions = validateSkuMdOptions(options.skuMd, {
      siteUrl,
      routeBasePath,
      merchantName: homePage.title,
      summary: homePage.description,
    });
    generatorOptions.skuMd = skuMdOptions;
  }

  addFile('llms.txt', generateLlmsTxt(
    siteMetadata,
    pageModels.map((page) => page.filePath),
    distDir,
    generatorOptions,
  ));
  if (generatorOptions.generateRobots) {
    addFile('robots.txt', generateRobotsTxt(siteMetadata.url, {
      routeBasePath,
      robotsDirectives: options.robotsDirectives || [],
      sitemapUrl: generatorOptions.sitemapUrl,
      includeSitemap: generatorOptions.includeSitemap,
    }));
  }
  if (options.generateHumans === true) {
    if (!packageJson) {
      throw new Error('generateHumans requires a readable package.json.');
    }
    addFile('humans.txt', generateHumansTxt(packageJson, currentDate, {
      extractTeamInfoFromPackageJson,
      extractTechStackFromPackageJson,
    }));
  }

  const htmlUpdates = [];
  const discoveryByPath = new Map();
  const feedHref = `${routeBasePath || '/'}feed.xml`.replace(/\/{2,}/g, '/');
  if (options.generateFeed !== false) {
    const feedPages = pageModels.map((page) => ({
      url: composePageUrl(siteMetadata.url, page.pagePath, routeBasePath),
      title: page.title || 'Untitled',
      description: page.description || '',
      mtime: page.mtime,
    }));
    addFile('feed.xml', generateFeedXml(feedPages, {
      ...siteMetadata,
      feedUrl: composePageUrl(siteMetadata.url, 'feed.xml', routeBasePath),
    }, currentDate));
  }

  pageModels.forEach((page) => {
    let content = page.htmlContent;
    if (options.generateFeed !== false) {
      content = injectFeedLink(content, feedHref);
    }
    content = injectLlmsDiscoveryLinks(content, {
      markdownUrl: page.markdownUrl,
      llmsUrl,
      pageUrl: page.pageUrl,
      // If nothing was injected, reuse the initial facts for headless documents.
      inspectionFacts: content === page.htmlContent ? page.audit : undefined,
      onInspect: options.audit !== false ? (documentAst, addedLinks, existingFacts) => {
        const facts = existingFacts || collectAuditFacts(documentAst, { discoveryOnly: true });
        facts.links.push(...addedLinks);
        discoveryByPath.set(page.relativePath, facts);
      } : undefined,
    });
    if (content !== page.htmlContent) {
      htmlUpdates.push({ filename: page.relativePath, content });
    }
  });

  if (skuMdOptions) {
    addFile('sku.md', generateSkuMd(skuMdOptions, { siteUrl }));
  }

  return {
    files,
    htmlUpdates,
    report: {
      totalHtmlFiles: allPageModels.length,
      includedHtmlFiles: pageModels.length,
      excludedHtmlFiles: excluded.length,
      excludedDetails,
      routeConflicts,
      siteUrl,
      routeBasePath,
      sitemapCompatibility,
      robotsCompatibility,
      ...(options.audit !== false ? { audit: auditGeoPlan({
        allPages: allPageModels,
        pages: pageModels,
        homePage,
        files,
        existingFiles: outputAssets,
        options: generatorOptions,
        siteUrl,
        sitemapGenerated: sitemapCompatibility.shouldGenerateSitemap,
        discoveryByPath,
      }) } : {}),
      generatedFiles: files.map(({ filename, content }) => ({
        filename,
        size: Buffer.byteLength(content, 'utf-8'),
      })),
    },
  };
}

export async function buildGeoGenerationPlanFromDisk({
  projectRoot,
  distDir,
  options = {},
  currentDate,
}) {
  if (!existsSync(distDir)) {
    throw new Error(`Dist directory not found: ${distDir}`);
  }
  const htmlInputs = findHtmlFiles(distDir).map((filePath) => ({
    filePath,
    relativePath: normalizeFilePath(relative(distDir, filePath)),
    htmlContent: readFileSync(filePath, 'utf-8'),
  }));
  return buildGeoGenerationPlan({
    projectRoot,
    distDir,
    htmlInputs,
    outputAssets: listExistingOutputAssets(distDir),
    options,
    currentDate,
  });
}

export function applyGeoGenerationPlanToDisk(plan, { distDir }) {
  const entries = [...plan.files, ...plan.htmlUpdates];
  if (entries.length === 0) return;

  mkdirSync(distDir, { recursive: true });
  const stageDir = mkdtempSync(join(distDir, '.vite-plugin-geo-stage-'));
  const backupDir = mkdtempSync(join(distDir, '.vite-plugin-geo-backup-'));
  const appliedTargets = [];
  const backedUpTargets = [];

  try {
    entries.forEach(({ filename, content }) => {
      const stagedPath = resolve(stageDir, filename);
      mkdirSync(dirname(stagedPath), { recursive: true });
      writeFileSync(stagedPath, content, 'utf-8');
    });

    entries.forEach(({ filename }) => {
      const targetPath = resolve(distDir, filename);
      const stagedPath = resolve(stageDir, filename);
      const backupPath = resolve(backupDir, filename);
      mkdirSync(dirname(targetPath), { recursive: true });
      if (existsSync(targetPath)) {
        mkdirSync(dirname(backupPath), { recursive: true });
        renameSync(targetPath, backupPath);
        backedUpTargets.push({ targetPath, backupPath });
      }
      renameSync(stagedPath, targetPath);
      appliedTargets.push(targetPath);
    });
  } catch (error) {
    appliedTargets.reverse().forEach((targetPath) => {
      rmSync(targetPath, { force: true });
    });
    backedUpTargets.reverse().forEach(({ targetPath, backupPath }) => {
      if (existsSync(backupPath)) {
        mkdirSync(dirname(targetPath), { recursive: true });
        renameSync(backupPath, targetPath);
      }
    });
    throw error;
  } finally {
    rmSync(stageDir, { recursive: true, force: true });
    rmSync(backupDir, { recursive: true, force: true });
  }
}
