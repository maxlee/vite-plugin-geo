import { afterEach, describe, expect, it, vi } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { join } from 'path';
import {
  applyGeoGenerationPlanToDisk,
  buildGeoGenerationPlanFromDisk,
  logRobotsPreservation,
} from '../geoBuildPipeline.js';
import { runSeoCliGenerate } from '../cli.js';

const roots = [];
const userRobots = Buffer.from('# 手写规则\r\nUser-agent: *\r\nDisallow: /private/\r\n');
function fixture(robots) {
  const parent = join(process.cwd(), 'tempfiles');
  mkdirSync(parent, { recursive: true });
  const root = mkdtempSync(join(parent, 'robots-compat-'));
  roots.push(root);
  const distDir = join(root, 'dist');
  mkdirSync(distDir);
  writeFileSync(join(root, 'package.json'), JSON.stringify({ name: 'robots-test', domain: 'https://example.com' }));
  writeFileSync(join(distDir, 'index.html'), '<html lang="en"><head><title>Home</title><meta name="description" content="Home page"></head><body><h1>Home</h1></body></html>');
  if (robots !== undefined) writeFileSync(join(distDir, 'robots.txt'), robots);
  return { root, distDir };
}
function planFor({ root, distDir }, options = {}) {
  return buildGeoGenerationPlanFromDisk({ projectRoot: root, distDir, options });
}
function snapshot(directory) {
  return readdirSync(directory).sort().map(name => [name, readFileSync(join(directory, name))]);
}
afterEach(() => {
  roots.splice(0).forEach(root => rmSync(root, { recursive: true, force: true }));
});

describe('existing robots compatibility', () => {
  it.each([['user rules', userRobots], ['empty user file', Buffer.alloc(0)]])('preserves %s byte for byte while generating other artifacts', async (_label, robots) => {
    const context = fixture(robots);
    const plan = await planFor(context);
    expect(plan.report.robotsCompatibility).toEqual({ preserved: true, directivesIgnored: false });
    expect(plan.files.map(file => file.filename)).not.toContain('robots.txt');
    expect(plan.files.map(file => file.filename)).toEqual(expect.arrayContaining(['sitemap.xml', 'llms.txt', 'feed.xml', 'index.md']));
    expect(plan.files.find(file => file.filename === 'llms.txt').content).toContain('https://example.com/robots.txt');
    applyGeoGenerationPlanToDisk(plan, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'))).toEqual(robots);
    expect(readFileSync(join(context.distDir, 'index.html'), 'utf-8')).toContain('application/rss+xml');
    const repeated = await planFor(context);
    applyGeoGenerationPlanToDisk(repeated, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'))).toEqual(robots);
  });

  it.each([
    ['incidental marker mention', '# Replaces previous Generated by vite-plugin-geo setup\nUser-agent: *\nDisallow: /private/\n'],
    ['marker on a later line', '# User maintained\n# Generated by vite-plugin-geo\nUser-agent: *\nDisallow: /private/\n'],
  ])('treats %s as user owned for preservation and explicit generation', async (_label, robots) => {
    const context = fixture(robots);
    const plan = await planFor(context);
    expect(plan.report.robotsCompatibility).toEqual({ preserved: true, directivesIgnored: false });
    expect(plan.files.map(file => file.filename)).not.toContain('robots.txt');
    applyGeoGenerationPlanToDisk(plan, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'), 'utf-8')).toBe(robots);
    const before = snapshot(context.distDir);
    await expect(runSeoCliGenerate({ generateRobots: true }, {
      cwd: context.root, logger: { log() {}, warn() {}, error() {} },
    })).rejects.toThrow(/robots\.txt.*generateRobots:\s*false/i);
    expect(snapshot(context.distDir)).toEqual(before);
  });

  it('generates robots when absent and regenerates managed output with current directives', async () => {
    const context = fixture();
    const first = await planFor(context);
    expect(first.report.robotsCompatibility).toEqual({ preserved: false, directivesIgnored: false });
    applyGeoGenerationPlanToDisk(first, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'), 'utf-8')).toContain('# Generated by vite-plugin-geo');
    const next = await planFor(context, { robotsDirectives: ['Disallow: /new-private/'] });
    expect(next.report.robotsCompatibility.preserved).toBe(false);
    const generated = next.files.find(file => file.filename === 'robots.txt').content;
    expect(generated).toContain('Disallow: /new-private/');
    applyGeoGenerationPlanToDisk(next, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'), 'utf-8')).toBe(generated);
  });

  it.each([
    ['absent', undefined],
    ['user owned', userRobots],
    ['plugin managed', '# Generated by vite-plugin-geo\nUser-agent: *\n'],
  ])('generateRobots:false never writes %s robots', async (_label, robots) => {
    const context = fixture(robots);
    const plan = await planFor(context, { generateRobots: false });
    expect(plan.files.map(file => file.filename)).not.toContain('robots.txt');
    applyGeoGenerationPlanToDisk(plan, context);
    if (robots === undefined) expect(existsSync(join(context.distDir, 'robots.txt'))).toBe(false);
    else expect(readFileSync(join(context.distDir, 'robots.txt'))).toEqual(Buffer.from(robots));
  });

  it.each([userRobots, Buffer.alloc(0)])('rejects explicit generation before changing any output', async robots => {
    const context = fixture(robots);
    const before = snapshot(context.distDir);
    const logger = { log: vi.fn(), warn: vi.fn(), error: vi.fn() };
    await expect(runSeoCliGenerate({ generateRobots: true }, { cwd: context.root, logger }))
      .rejects.toThrow(/robots\.txt.*generateRobots:\s*false/i);
    expect(snapshot(context.distDir)).toEqual(before);
  });

  it('still rejects a conflicting user feed without changing any output', async () => {
    const context = fixture(userRobots);
    writeFileSync(join(context.distDir, 'feed.xml'), '<rss>User owned feed</rss>');
    const before = snapshot(context.distDir);
    await expect(runSeoCliGenerate({}, { cwd: context.root, logger: { log() {}, warn() {}, error() {} } }))
      .rejects.toThrow(/feed\.xml.*existing user file/i);
    expect(snapshot(context.distDir)).toEqual(before);
  });

  it.each([{}, { audit: false, debug: false }])('reports CLI preservation with options %j', async options => {
    const context = fixture(userRobots);
    const logger = { log: vi.fn(), warn: vi.fn(), error: vi.fn() };
    await runSeoCliGenerate(options, { cwd: context.root, logger });
    expect(logger.log.mock.calls.flat().join('\n')).toMatch(/\[vite-plugin-geo\].*preserv.*robots\.txt/i);
  });

  it('ignores custom directives while preserving robots and explains it through the shared logger', async () => {
    const context = fixture(userRobots);
    const plan = await planFor(context, { robotsDirectives: ['Disallow: /added/'], audit: false, debug: false });
    expect(plan.report.robotsCompatibility).toEqual({ preserved: true, directivesIgnored: true });
    const logger = { log: vi.fn(), warn: vi.fn() };
    logRobotsPreservation(plan.report.robotsCompatibility, logger);
    expect(logger.warn.mock.calls.flat().join('\n')).toMatch(/\[vite-plugin-geo\].*robotsDirectives.*not applied/i);
    applyGeoGenerationPlanToDisk(plan, context);
    expect(readFileSync(join(context.distDir, 'robots.txt'))).toEqual(userRobots);
    logger.warn.mockClear();
    await runSeoCliGenerate({ robotsDirectives: ['Disallow: /added/'], audit: false, debug: false }, { cwd: context.root, logger });
    expect(logger.warn.mock.calls.flat().join('\n')).toMatch(/\[vite-plugin-geo\].*robotsDirectives.*not applied/i);
  });
});
