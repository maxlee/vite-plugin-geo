import { afterEach, describe, expect, it, vi } from 'vitest';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { build as buildVite7 } from 'vite7';
import { build as buildVite8 } from 'vite8';
import { createGeoGeneratorPlugin } from '../src/viteGeoGeneratorPlugin.js';

const fixtureRoot = join(process.cwd(), 'tempfiles', '__real-vite-builds__');

function writeFixture(root, relativePath, content) {
  const filePath = join(root, relativePath);
  mkdirSync(dirname(filePath), { recursive: true });
  writeFileSync(filePath, content, 'utf-8');
}

afterEach(() => {
  rmSync(fixtureRoot, { recursive: true, force: true });
});

describe('real Vite builds', () => {
  it.each([
    ['Vite 7', buildVite7],
    ['Vite 8', buildVite8],
  ])('generates the same core outputs with %s', async (_label, viteBuild) => {
    const root = join(fixtureRoot, _label.replace(/\s+/g, '-').toLowerCase());
    const distDir = join(root, 'dist');
    writeFixture(root, 'package.json', JSON.stringify({
      name: 'vite-real-build',
      domain: 'https://example.com',
    }));
    writeFixture(
      root,
      'index.html',
      '<!doctype html><html lang="en"><head><title>Real Vite</title><meta name="description" content="Real build"></head><body><h1>Home</h1></body></html>',
    );

    await viteBuild({
      root,
      configFile: false,
      logLevel: 'silent',
      plugins: [createGeoGeneratorPlugin({
        packageJsonPath: join(root, 'package.json'),
        lastmodStrategy: 'git',
        skuMd: {
          merchantName: 'Real Store',
          summary: 'Real storefront catalog.',
          catalog: [{ label: 'Catalog', url: 'https://example.com/catalog' }],
        },
      })],
      build: {
        outDir: distDir,
        emptyOutDir: true,
      },
    });

    expect(readFileSync(join(distDir, 'index.html'), 'utf-8')).toContain('application/rss+xml');
    expect(existsSync(join(distDir, 'sitemap.xml'))).toBe(true);
    expect(existsSync(join(distDir, 'robots.txt'))).toBe(true);
    expect(existsSync(join(distDir, 'llms.txt'))).toBe(true);
    expect(existsSync(join(distDir, 'index.md'))).toBe(true);
    expect(existsSync(join(distDir, 'sku.md'))).toBe(true);
    expect(readFileSync(join(distDir, 'sitemap.xml'), 'utf-8')).not.toContain('<lastmod>');
  }, 20_000);

  const publicCases = [
    ['default public directory', {}, 'public', true],
    ['custom public directory', { publicDir: 'static' }, 'static', true],
    ['disabled public directory', { publicDir: false }, 'public', false],
    ['disabled public copying', { build: { copyPublicDir: false } }, 'public', false],
  ];
  describe.each([['Vite 7', buildVite7], ['Vite 8', buildVite8]])('%s public robots', (label, viteBuild) => {
    it.each(publicCases)('%s', async (name, config, directory, preserve) => {
      const root = join(fixtureRoot, `${label}-${name}`.replace(/\s+/g, '-'));
      const robots = Buffer.from('# 手写规则\r\nUser-agent: *\r\nDisallow: /private/\r\n');
      writeFixture(root, 'package.json', JSON.stringify({ name: 'public-robots-test', domain: 'https://example.com' }));
      writeFixture(root, 'index.html', '<html lang="en"><head><title>Public robots</title></head><body><h1>Home</h1></body></html>');
      writeFixture(root, `${directory}/robots.txt`, robots);
      await viteBuild({
        root, configFile: false, logLevel: 'silent', ...config,
        plugins: [createGeoGeneratorPlugin({ audit: false, debug: false })],
        build: { ...config.build, outDir: join(root, 'dist'), emptyOutDir: true },
      });
      const result = readFileSync(join(root, 'dist/robots.txt'));
      if (preserve) expect(result).toEqual(robots);
      else {
        expect(result.toString()).toContain('# Generated by vite-plugin-geo');
        expect(result.toString()).not.toContain('/private/');
      }
      expect(readFileSync(join(root, 'dist/llms.txt'), 'utf-8')).toContain('https://example.com/robots.txt');
      expect(existsSync(join(root, 'dist/sitemap.xml'))).toBe(true);
      expect(existsSync(join(root, 'dist/feed.xml'))).toBe(true);
    }, 20_000);

    it('preserves robots emitted by another bundle plugin', async () => {
      const root = join(fixtureRoot, `${label}-bundled-robots`.replace(/\s+/g, '-'));
      const robots = '# Bundle rules\nUser-agent: *\nDisallow: /bundle-private/\n';
      writeFixture(root, 'package.json', JSON.stringify({ name: 'bundled-robots-test', domain: 'https://example.com' }));
      writeFixture(root, 'index.html', '<html><head><title>Bundle robots</title></head><body>Home</body></html>');
      await viteBuild({
        root, configFile: false, logLevel: 'silent', publicDir: false,
        plugins: [
          { name: 'user-robots', generateBundle() { this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots }); } },
          createGeoGeneratorPlugin({ audit: false }),
        ],
        build: { outDir: join(root, 'dist'), emptyOutDir: true },
      });
      expect(readFileSync(join(root, 'dist/robots.txt'), 'utf-8')).toBe(robots);
      expect(readFileSync(join(root, 'dist/llms.txt'), 'utf-8')).toContain('https://example.com/robots.txt');
    }, 20_000);

    it('preserves public companion files and mirror collisions by default', async () => {
      const root = join(fixtureRoot, `${label}-public-companions`.replace(/\s+/g, '-'));
      const publicFiles = {
        'public/llms.txt': '# User llms\n',
        'public/feed.xml': '<rss>User feed</rss>',
        'public/humans.txt': 'User humans\n',
        'public/sku.md': '# User SKU\n',
        'public/about.md': '# User About\n',
      };
      writeFixture(root, 'package.json', JSON.stringify({ name: 'public-companions', domain: 'https://example.com' }));
      writeFixture(root, 'index.html', '<html lang="en"><head><title>Home</title><meta name="description" content="Home"></head><body><h1>Home</h1></body></html>');
      writeFixture(root, 'about.html', '<html lang="en"><head><title>About</title><meta name="description" content="About"></head><body><h1>About</h1></body></html>');
      Object.entries(publicFiles).forEach(([path, content]) => writeFixture(root, path, content));

      const warnings = [];
      const warnSpy = vi.spyOn(console, 'warn').mockImplementation((...args) => warnings.push(args.join(' ')));
      try {
        for (let build = 0; build < 2; build += 1) {
          await viteBuild({
            root, configFile: false, logLevel: 'silent',
            plugins: [createGeoGeneratorPlugin({
              audit: false,
              generateHumans: true,
              skuMd: {
                merchantName: 'Public Store',
                summary: 'Public store',
                catalog: [{ label: 'Home', url: 'https://example.com/' }],
              },
            })],
            build: {
              outDir: join(root, 'dist'),
              emptyOutDir: true,
              rollupOptions: { input: [join(root, 'index.html'), join(root, 'about.html')] },
            },
          });

          Object.entries(publicFiles).forEach(([path, content]) => {
            expect(readFileSync(join(root, 'dist', path.replace(/^public\//, '')), 'utf-8')).toBe(content);
          });
          expect(existsSync(join(root, 'dist/sitemap.xml'))).toBe(true);
          expect(existsSync(join(root, 'dist/robots.txt'))).toBe(true);
          expect(existsSync(join(root, 'dist/index.md'))).toBe(true);
          expect(readFileSync(join(root, 'dist/index.html'), 'utf-8')).toContain('application/rss+xml');
        }
      } finally {
        warnSpy.mockRestore();
      }
      expect(warnings.join('\n')).toMatch(/Preserved .*about\.md/i);
    }, 30_000);

    it('preserves llms.txt and feed.xml emitted by another bundle plugin', async () => {
      const root = join(fixtureRoot, `${label}-bundled-companions`.replace(/\s+/g, '-'));
      const llms = '# Bundle llms\n';
      const feed = '<rss>Bundle feed</rss>';
      writeFixture(root, 'package.json', JSON.stringify({ name: 'bundled-companions', domain: 'https://example.com' }));
      writeFixture(root, 'index.html', '<html><head><title>Bundle companions</title></head><body>Home</body></html>');
      await viteBuild({
        root, configFile: false, logLevel: 'silent', publicDir: false,
        plugins: [
          {
            name: 'user-companions',
            generateBundle() {
              this.emitFile({ type: 'asset', fileName: 'llms.txt', source: llms });
              this.emitFile({ type: 'asset', fileName: 'feed.xml', source: feed });
            },
          },
          createGeoGeneratorPlugin({ audit: false, llmsMdMirror: false }),
        ],
        build: { outDir: join(root, 'dist'), emptyOutDir: true },
      });
      expect(readFileSync(join(root, 'dist/llms.txt'), 'utf-8')).toBe(llms);
      expect(readFileSync(join(root, 'dist/feed.xml'), 'utf-8')).toBe(feed);
      expect(existsSync(join(root, 'dist/sitemap.xml'))).toBe(true);
      expect(existsSync(join(root, 'dist/robots.txt'))).toBe(true);
    }, 20_000);
  });

});
