import { afterEach, describe, expect, it } from 'vitest';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { buildGeoGenerationPlanFromDisk } from '../src/geoBuildPipeline.js';
import { createGeoGeneratorPlugin } from '../src/viteGeoGeneratorPlugin.js';

const roots = [];

const EXTERNAL_SITEMAP = '<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>https://example.test/old</loc></url></urlset>';
const MANAGED_SITEMAP = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by vite-plugin-geo -->\n<urlset><url><loc>https://example.test/</loc></url></urlset>';

function page(title) {
  return `<html lang="en"><head><title>${title}</title><meta name="description" content="${title} desc"></head><body><h1>${title}</h1></body></html>`;
}

function fixture({ sitemap } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'geo-sitemap-conflict-'));
  roots.push(root);
  const distDir = join(root, 'dist');
  mkdirSync(distDir, { recursive: true });
  writeFileSync(join(root, 'package.json'), JSON.stringify({ name: 'sitemap-fixture', domain: 'https://example.test' }));
  writeFileSync(join(distDir, 'index.html'), page('Home'));
  if (sitemap) writeFileSync(join(distDir, 'sitemap.xml'), sitemap);
  return { root, distDir };
}

function planFor(f, options = {}) {
  return buildGeoGenerationPlanFromDisk({
    projectRoot: f.root,
    distDir: f.distDir,
    currentDate: '2026-10-01T00:00:00.000Z',
    options: { generateFeed: false, llmsMdMirror: false, generateHumans: false, ...options },
  });
}

afterEach(() => {
  roots.splice(0).forEach((root) => rmSync(root, { recursive: true, force: true }));
});

describe('sitemap conflict policy', () => {
  it('preserves a third-party sitemap by default and reports what it found', async () => {
    const f = fixture({ sitemap: EXTERNAL_SITEMAP });
    const plan = await planFor(f);

    expect(plan.files.some(({ filename }) => filename === 'sitemap.xml')).toBe(false);
    expect(plan.report.sitemapCompatibility).toMatchObject({
      detected: true,
      decision: 'preserve',
      shouldGenerateSitemap: false,
      sitemapUrl: 'sitemap.xml',
      existing: {
        filename: 'sitemap.xml',
        locCount: 1,
        samples: ['https://example.test/old'],
        managed: false,
      },
    });
    expect(plan.files.find(({ filename }) => filename === 'robots.txt')?.content)
      .toContain('Sitemap: https://example.test/sitemap.xml');
  });

  it('throws for explicit generateSitemap:true without an explicit policy', async () => {
    const f = fixture({ sitemap: EXTERNAL_SITEMAP });
    await expect(planFor(f, { generateSitemap: true })).rejects.toThrow(
      /Another plugin \(or a public\/ file\) generated it.*sitemapConflict: 'overwrite'/s,
    );
  });

  it('throws for sitemapConflict:error', async () => {
    const f = fixture({ sitemap: EXTERNAL_SITEMAP });
    await expect(planFor(f, { sitemapConflict: 'error' })).rejects.toThrow(/existing sitemap/);
  });

  it('overwrites only when explicitly requested', async () => {
    const f = fixture({ sitemap: EXTERNAL_SITEMAP });
    const plan = await planFor(f, { sitemapConflict: 'overwrite' });
    const sitemap = plan.files.find(({ filename }) => filename === 'sitemap.xml')?.content || '';

    expect(plan.report.sitemapCompatibility.decision).toBe('overwrite');
    expect(sitemap).toContain('Generated by vite-plugin-geo');
    expect(sitemap).toContain('<loc>https://example.test</loc>');
    expect(sitemap).not.toContain('/old');
  });

  it('preserve wins over explicit generateSitemap:true', async () => {
    const f = fixture({ sitemap: EXTERNAL_SITEMAP });
    const plan = await planFor(f, { generateSitemap: true, sitemapConflict: 'preserve' });

    expect(plan.report.sitemapCompatibility.decision).toBe('preserve');
    expect(plan.files.some(({ filename }) => filename === 'sitemap.xml')).toBe(false);
  });

  it('regenerates a sitemap previously written by vite-plugin-geo', async () => {
    const f = fixture({ sitemap: MANAGED_SITEMAP });
    const plan = await planFor(f);

    expect(plan.report.sitemapCompatibility).toMatchObject({
      decision: 'regenerate',
      shouldGenerateSitemap: true,
    });
    expect(plan.files.some(({ filename }) => filename === 'sitemap.xml')).toBe(true);
  });

  it('detects a sitemap copied from public/ before Vite copies it', async () => {
    const f = fixture();
    const publicDir = join(f.root, 'public');
    mkdirSync(publicDir, { recursive: true });
    writeFileSync(join(publicDir, 'sitemap.xml'), EXTERNAL_SITEMAP);

    const plugin = createGeoGeneratorPlugin({
      domain: 'https://example.test',
      generateFeed: false,
      llmsMdMirror: false,
    });
    plugin.configResolved({
      root: f.root,
      base: '/',
      publicDir,
      build: { outDir: 'dist', copyPublicDir: true },
    });

    const emitted = [];
    const messages = [];
    const originalWarn = console.warn;
    const originalLog = console.log;
    console.warn = (...args) => messages.push(args.join(' '));
    console.log = (...args) => messages.push(args.join(' '));
    try {
      await plugin.generateBundle.handler.call(
        { emitFile: ({ fileName }) => emitted.push(fileName), meta: {} },
        { dir: f.distDir },
        {
          'index.html': { type: 'asset', fileName: 'index.html', source: page('Home') },
        },
      );
    } finally {
      console.warn = originalWarn;
      console.log = originalLog;
    }

    expect(emitted).not.toContain('sitemap.xml');
    expect(messages.join('\n')).toMatch(/保留现有 sitemap.*来源：publicDir/);
  });
});
